// Classic 5x7 bitmap font (ASCII 32..95), column-major, bit 0 = top row.
// Packed as 2 u32 per glyph for the GPU text overlay (no DOM text updates per frame).
const HEX =
  '0000000000' + '00005f0000' + '0007000700' + '147f147f14' + '242a7f2a12' + '2313086462' + '3649552250' + '0005030000' +
  '001c224100' + '0041221c00' + '082a1c2a08' + '08083e0808' + '0050300000' + '0808080808' + '0060600000' + '2010080402' +
  '3e5149453e' + '00427f4000' + '4261514946' + '2141454b31' + '1814127f10' + '2745454539' + '3c4a494930' + '0171090503' +
  '3649494936' + '064949291e' + '0036360000' + '0056360000' + '0008142241' + '1414141414' + '4122140800' + '0201510906' +
  '324979413e' + '7e1111117e' + '7f49494936' + '3e41414122' + '7f4141221c' + '7f49494941' + '7f09090101' + '3e41415132' +
  '7f0808087f' + '00417f4100' + '2040413f01' + '7f08142241' + '7f40404040' + '7f0204027f' + '7f0408107f' + '3e4141413e' +
  '7f09090906' + '3e4151215e' + '7f09192946' + '4649494931' + '01017f0101' + '3f4040403f' + '1f2040201f' + '7f2018207f' +
  '6314081463' + '0304780403' + '6151494543' + '00007f4141' + '0204081020' + '41417f0000' + '0402010204' + '4040404040';

export const FONT_WORDS: Uint32Array = (() => {
  const out = new Uint32Array(64 * 2);
  for (let g = 0; g < 64; g++) {
    const b = (i: number) => parseInt(HEX.substr(g * 10 + i * 2, 2), 16);
    out[g * 2] = (b(0) | (b(1) << 8) | (b(2) << 16) | (b(3) << 24)) >>> 0;
    out[g * 2 + 1] = b(4);
  }
  return out;
})();
